const express = require("express");
const bcrypt = require("bcryptjs");
const jwt = require("jsonwebtoken");
const Requester = require("../models/Requester");
const { sendOtp, checkOtp } = require("../utils/otp");
const requireRequester = require("../middleware/requireRequester");
const router = express.Router();

const cleanPhone = value => String(value || "").replace(/[^0-9]/g, "").slice(-10);
const publicRequester = requester => ({ _id: requester._id, name: requester.name, phone: requester.phone, district: requester.district || requester.city, state: requester.state });

function tokenFor(requester) {
  return jwt.sign({ id: requester._id, phone: requester.phone, role: "requester" }, process.env.JWT_SECRET, { expiresIn: "30d" });
}

router.post("/send-otp", async (req, res) => {
  try {
    const phone = cleanPhone(req.body?.phone);
    if (!/^[6-9]\d{9}$/.test(phone)) return res.status(400).json({ error: "Enter a valid 10-digit Indian mobile number." });
    const result = await sendOtp(phone);
    res.json({ message: "Demo OTP generated.", ...result });
  } catch (err) {
    res.status(500).json({ error: "Unable to generate OTP right now." });
  }
});

router.post("/register", async (req, res) => {
  try {
    const { name, password, otp, district, city, state } = req.body || {};
    const cleanDistrict = String(district || city || "").trim();
    const phone = cleanPhone(req.body?.phone);
    if (!name?.trim() || name.trim().length > 100 || !cleanDistrict || !state?.trim()) return res.status(400).json({ error: "Name, district and state are required." });
    if (!/^[6-9]\d{9}$/.test(phone)) return res.status(400).json({ error: "Enter a valid 10-digit Indian mobile number." });
    if (typeof password !== "string" || password.length < 6) return res.status(400).json({ error: "Password must be at least 6 characters." });
    if (!await checkOtp(phone, otp)) return res.status(400).json({ error: "Incorrect or expired OTP. Request a new code." });
    const passwordHash = await bcrypt.hash(password, 10);
    const requester = await Requester.findOneAndUpdate(
      { phone },
      { $set: { name: name.trim(), passwordHash, district: cleanDistrict, city: cleanDistrict, state: state.trim() } },
      { new: true, upsert: true, runValidators: true, setDefaultsOnInsert: true }
    );
    res.status(201).json({ requester: publicRequester(requester), token: tokenFor(requester) });
  } catch (err) {
    if (err.code === 11000) return res.status(409).json({ error: "An account with this mobile number already exists. Please log in." });
    res.status(500).json({ error: "Unable to create requester account right now." });
  }
});

router.post("/login", async (req, res) => {
  try {
    const phone = cleanPhone(req.body?.phone);
    const password = req.body?.password;
    if (!phone || !password) return res.status(400).json({ error: "Mobile number and password are required." });
    const requester = await Requester.findOne({ phone });
    if (!requester || !await bcrypt.compare(password, requester.passwordHash)) return res.status(401).json({ error: "Invalid mobile number or password." });
    res.json({ requester: publicRequester(requester), token: tokenFor(requester) });
  } catch {
    res.status(500).json({ error: "Unable to log in right now." });
  }
});

// Demo-mode password recovery: OTP is generated by the backend and returned only in demo mode.
router.post("/forgot-password/send-otp", async (req, res) => {
  try {
    const phone = cleanPhone(req.body?.phone);
    if (!/^[6-9]\d{9}$/.test(phone)) return res.status(400).json({ error: "Enter a valid 10-digit Indian mobile number." });
    const requester = await Requester.findOne({ phone });
    if (!requester) return res.status(404).json({ error: "No requester account found with that mobile number." });
    const result = await sendOtp(phone);
    res.json({ message: "Password reset OTP generated.", ...result });
  } catch {
    res.status(500).json({ error: "Unable to generate password reset OTP right now." });
  }
});

router.post("/forgot-password/reset", async (req, res) => {
  try {
    const phone = cleanPhone(req.body?.phone);
    const { otp, newPassword } = req.body || {};
    if (!/^[6-9]\d{9}$/.test(phone) || !otp || typeof newPassword !== "string") return res.status(400).json({ error: "Mobile number, OTP and new password are required." });
    if (newPassword.length < 6) return res.status(400).json({ error: "New password must be at least 6 characters." });
    const requester = await Requester.findOne({ phone });
    if (!requester) return res.status(404).json({ error: "No requester account found with that mobile number." });
    if (!await checkOtp(phone, otp)) return res.status(400).json({ error: "Incorrect or expired OTP. Request a new code." });
    requester.passwordHash = await bcrypt.hash(newPassword, 10);
    await requester.save();
    res.json({ message: "Password reset successfully. You can now log in." });
  } catch {
    res.status(500).json({ error: "Unable to reset password right now." });
  }
});

router.get("/me", requireRequester, async (req, res) => {
  const requester = await Requester.findById(req.requester.id);
  if (!requester) return res.status(404).json({ error: "Requester account not found." });
  res.json(publicRequester(requester));
});

module.exports = router;
